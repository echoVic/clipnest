type testClipboard struct {
	access    ClipboardAccess
	revision  int64
	formats   []string
	portable  []transfer.Format
	text      []byte
	image     []byte
	readErr   error
	reads     int
	onRead    func()
	onFormats func()
}

func (c *testClipboard) Revision() int64                  { return c.revision }
func (c *testClipboard) ClipboardAccess() ClipboardAccess { return c.access }
func (c *testClipboard) AvailableFormats() []string       { return c.formats }
func (c *testClipboard) Formats() []transfer.Format {
	if c.onFormats != nil {
		c.onFormats()
	}
	return c.portable
}
func (c *testClipboard) Target() targetApp { return targetApp{Name: "Test app"} }
func (c *testClipboard) ReadFormat(transfer.Format) ([]byte, error) {
	c.reads++
	if c.onRead != nil {
		c.onRead()
	}
	return c.text, c.readErr
}
func (c *testClipboard) ReadImage() []byte {
	c.reads++
	if c.onRead != nil {
		c.onRead()
	}
	return c.image
}

func clipboardDesktop(t *testing.T) *Desktop {
	t.Helper()
	s, err := openStorage(t.TempDir())
	if err != nil {
		t.Fatal(err)
	}
	t.Cleanup(func() { _ = s.Close() })
	return &Desktop{h: s.History, lastRevision: -2}
}

func clipboardHistoryCount(t *testing.T, d *Desktop) int {
	t.Helper()
	v, err := d.h.OpenView()
	if err != nil {
		t.Fatal(err)
	}
	defer v.Close()
	page, err := v.Page("", "", 0, 50)
	if err != nil {
		t.Fatal(err)
	}
	return page.Total
}

func TestClipboardBackgroundNeverRequestsPermission(t *testing.T) {
	for _, access := range []ClipboardAccess{clipboardDefault, clipboardAsk, clipboardDenied, clipboardUnknown} {
		t.Run(string(access), func(t *testing.T) {
			d := clipboardDesktop(t)
			c := &testClipboard{access: access, revision: 1, portable: []transfer.Format{transfer.Text}, text: []byte("private")}
			for i := 0; i < 3; i++ {
				if captured, err := d.captureFrom(c, false); captured || err != nil {
					t.Fatalf("unexpected capture: %v %v", captured, err)
				}
			}
			if c.reads != 0 || clipboardHistoryCount(t, d) != 0 || d.clipboardAccess != access {
				t.Fatal("background access read content or lost permission status")
			}
		})
	}
}

func TestClipboardExplicitReadOnlyInPermittedStates(t *testing.T) {
	for _, access := range []ClipboardAccess{clipboardDefault, clipboardAsk, clipboardAllowed, clipboardUnsupported, clipboardDenied, clipboardUnknown} {
		t.Run(string(access), func(t *testing.T) {
			d := clipboardDesktop(t)
			c := &testClipboard{access: access, revision: 1, portable: []transfer.Format{transfer.Text}, text: []byte("permission request")}
			captured, err := d.captureFrom(c, true)
			want := access != clipboardDenied && access != clipboardUnknown
			if err != nil || captured != want || c.reads != btoi(want) || clipboardHistoryCount(t, d) != btoi(want) {
				t.Fatalf("captured=%v reads=%d err=%v", captured, c.reads, err)
			}
		})
	}
}

func btoi(b bool) int {
	if b {
		return 1
	}
	return 0
}

func TestClipboardPermissionChangesWithoutNewCopy(t *testing.T) {
	d := clipboardDesktop(t)
	c := &testClipboard{access: clipboardDenied, revision: 1, portable: []transfer.Format{transfer.Text}, text: []byte("current")}
	_, _ = d.captureFrom(c, false)
	c.access = clipboardAllowed
	if captured, err := d.captureFrom(c, false); !captured || err != nil {
		t.Fatal("permission grant did not resume capture", err)
	}
	_, _ = d.captureFrom(c, false)
	c.access = clipboardDenied
	c.revision++
	_, _ = d.captureFrom(c, false)
	if c.reads != 1 || clipboardHistoryCount(t, d) != 1 || d.clipboardAccess != clipboardDenied {
		t.Fatal("duplicate read or read after revocation")
	}
}

func TestClipboardRequestStillIgnoresSensitiveUnsupportedAndPausedCopies(t *testing.T) {
	for _, marker := range []string{"org.nspasteboard.ConcealedType", "org.nspasteboard.TransientType", "org.nspasteboard.AutoGeneratedType", "file", "paused"} {
		t.Run(marker, func(t *testing.T) {
			d := clipboardDesktop(t)
			c := &testClipboard{access: clipboardAsk, revision: 1, formats: []string{marker}, portable: []transfer.Format{transfer.Text}, text: []byte("private")}
			if marker == "file" {
				c.portable = append(c.portable, transfer.FileList)
			}
			if marker == "paused" {
				d.h.Pause(true)
			}
			if captured, err := d.captureFrom(c, true); captured || err != nil || c.reads != 0 || clipboardHistoryCount(t, d) != 0 {
				t.Fatal("explicit request bypassed capture exclusions", captured, err)
			}
		})
	}
}

func TestClipboardReadCannotPersistAfterChangeOrRevocation(t *testing.T) {
	for _, change := range []string{"revision", "denied", "error"} {
		t.Run(change, func(t *testing.T) {
			d := clipboardDesktop(t)
			c := &testClipboard{access: clipboardAllowed, revision: 1, portable: []transfer.Format{transfer.Text}, text: []byte("private")}
			c.onRead = func() {
				switch change {
				case "revision":
					c.revision++
				case "denied":
					c.access = clipboardDenied
				case "error":
					c.readErr = errors.New("read denied")
				}
			}
			captured, err := d.captureFrom(c, false)
			if captured || clipboardHistoryCount(t, d) != 0 || (change == "error" && !errors.Is(err, c.readErr)) {
				t.Fatal("unreliable read was recorded", captured, err)
			}
		})
	}
}

func TestClipboardOneTimeReadDoesNotEnableBackgroundCapture(t *testing.T) {
	d := clipboardDesktop(t)
	c := &testClipboard{access: clipboardDefault, revision: 1, portable: []transfer.Format{transfer.Text}, text: []byte("once")}
	c.onRead = func() { c.access = clipboardAsk }
	if captured, err := d.captureFrom(c, true); !captured || err != nil {
		t.Fatal("one-time read failed", err)
	}
	c.revision++
	c.text = []byte("not authorized for background recording")
	if captured, err := d.captureFrom(c, false); captured || err != nil || c.reads != 1 || clipboardHistoryCount(t, d) != 1 {
		t.Fatal("one-time read enabled automatic recording", captured, err)
	}
}

func TestClipboardImagesFollowRecordingPermission(t *testing.T) {
	var data bytes.Buffer
	if err := png.Encode(&data, image.NewNRGBA(image.Rect(0, 0, 12, 8))); err != nil {
		t.Fatal(err)
	}
	for _, access := range []ClipboardAccess{clipboardAllowed, clipboardUnsupported, clipboardAsk, clipboardDenied} {
		t.Run(string(access), func(t *testing.T) {
			d := clipboardDesktop(t)
			c := &testClipboard{access: access, revision: 1, portable: []transfer.Format{transfer.PNG}, image: data.Bytes()}
			captured, err := d.captureFrom(c, false)
			want := access == clipboardAllowed || access == clipboardUnsupported
			if err != nil || captured != want || c.reads != btoi(want) || clipboardHistoryCount(t, d) != btoi(want) {
				t.Fatal("image permission ignored", captured, err)
			}
		})
	}
}

func TestClipboardMetadataChangeStopsBeforeContentRead(t *testing.T) {
	for _, change := range []string{"ask", "denied", "revision"} {
		t.Run(change, func(t *testing.T) {
			d := clipboardDesktop(t)
			c := &testClipboard{access: clipboardAllowed, revision: 1, portable: []transfer.Format{transfer.Text}, text: []byte("private")}
			c.onFormats = func() {
				switch change {
				case "ask":
					c.access = clipboardAsk
				case "denied":
					c.access = clipboardDenied
				case "revision":
					c.revision++
				}
			}
			if captured, err := d.captureFrom(c, false); captured || err != nil || c.reads != 0 || clipboardHistoryCount(t, d) != 0 {
				t.Fatal("metadata change still caused a content read", captured, err, c.reads)
			}
		})
	}
}
